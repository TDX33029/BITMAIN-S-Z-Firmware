//   折叠进第 0 轮 G 混合; rotr64(x,32) 被写成 32 位半字交换, rotr64(x,24/16/63)
//   写成半字移位组合; CARRY4(x,y) 为 32 位加法进位; VectorShiftLeft/VectorAdd
