//   输入 param_1 = blake2b_state 的 uint32 小端字视图:
//     state[0..15]  = h[0..7]  8 个 64 位链值 (state[2i] | state[2i+1]<<32)
//     state[16..19] = t[0..1]  64 位偏移计数器
